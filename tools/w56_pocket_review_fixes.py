#!/usr/bin/env python3
"""w56: fixes from the reviewer's Pocket Guide feedback (21 Nov 2026).

Post-processor. Run LAST (after w55), because the pocket pages and the six airport/station articles are
regenerated by w25 / w31 / w35 / w36 / w39 / w42. Idempotent (marker on pocket pages: id="savedOn";
on articles: the words "Ready offline").

What it does
1. Install order (iPhone keeps a separate copy for the home screen icon): add it first, open it from the icon
   while online, wait for "Ready offline". Pocket pages (sheet wording, next-guide card) and the six articles.
2. Status pill says "Ready offline" (was "Saved for offline use"); the header shows "Saved on this phone: date"
   (date of the last online open that refreshed the saved copy, kept in localStorage per home-screen copy).
3. Emergency block: 119 / 110 labelled "anywhere in Japan"; the airport/station information number is labelled
   "(not for emergencies)".
4. Narita and Haneda only: an "I'm connecting" button (Find tab and Arrive tab) with the official connection
   guidance (narita-airport.jp and tokyo-haneda.com connection pages, checked 21 Nov 2026).
5. Narita and Haneda only: a short line on the Arrive tab linking the other airports.
6. Narita only: health-form step wording matches Haneda (only if the flight gave a form).
7. Attribution: ?src= codes may be up to 40 characters, lower-cased, so partner codes such as yt-<creator>
   or agent-<name> are kept whole in pg_open (was cut at 20).
"""
import json, pathlib, re, sys

PUB = pathlib.Path(__file__).resolve().parent.parent / "public"
PAGES = ["narita", "haneda", "kix", "kyoto", "osaka", "tokyo", "shinjuku", "ueno"]
CHECKED = "21 November 2026"
OK = "Ready offline &#10003;"


def sub(s, old, new, name, count=1):
    n = s.count(old)
    if n != count:
        sys.exit(f"{name}: expected {count} x, found {n}: {old[:70]!r}")
    return s.replace(old, new)


