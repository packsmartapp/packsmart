PAINT = "  window.addEventListener('online',paint); window.addEventListener('offline',paint); paint();\n"
TICK = "  /* tick-off steps for arrival and departure */\n"


def fix_pocket(key):
    p = PUB / f"{key}-pocket.html"
    s = p.read_text(encoding="utf-8")
    if 'id="savedOn"' in s:
        print(f"  already  {p.name}"); return
    n = p.name

    # 1. install order wording
    s = sub(s, "Open it while you have signal, then add it to your home screen.",
            "Add it to your home screen, then open it from the icon while you have signal and wait for &ldquo;" + OK + "&rdquo;.", n + " next card",
            count=s.count("Open it while you have signal, then add it to your home screen."))
    lede_old = "h+='<p class=\"lede\">Do this once, now, while you have signal. Then it opens like an app, even with no internet.</p>';\n"
    ios_steps_old = "      h+=steps([[SHARE,'Tap the <b>Share</b> button (a square with an arrow) in Safari'],[PLUS,'Scroll down and tap <b>Add to Home Screen</b>'],['','Tap <b>Add</b>']]);\n"
    ios_new = ("h+='<p class=\"lede\">Do these in order, while you have signal. On iPhone the home screen icon can keep its own saved copy, so the order matters.</p>';\n"
               "      h+=steps([[SHARE,'Tap the <b>Share</b> button (a square with an arrow) in Safari'],[PLUS,'Scroll down and tap <b>Add to Home Screen</b>'],['','Tap <b>Add</b>'],"
               "['','Open the guide <b>from the new icon</b> on your home screen, while you have signal'],['','Wait until the top right says <b>" + OK + "</b>']]);\n")
    s = sub(s, lede_old + ios_steps_old, ios_new, n + " ios sheet")
    dots_old = "      h+=steps([[DOTS,'Tap the menu <b>&#8942;</b> (three dots) in your browser'],[DOWN,'Tap <b>Install app</b> or <b>Add to Home screen</b>'],['','Tap <b>Install</b> or <b>Add</b>']]);\n"
    gen_new = ("h+='<p class=\"lede\">Do this once, while you have signal.</p>';\n"
               "      h+=steps([[DOTS,'Tap the menu <b>&#8942;</b> (three dots) in your browser'],[DOWN,'Tap <b>Install app</b> or <b>Add to Home screen</b>'],['','Tap <b>Install</b> or <b>Add</b>'],"
               "['','Open the guide from the new icon and wait for <b>" + OK + "</b>']]);\n")
    s = sub(s, lede_old + dots_old, gen_new, n + " generic sheet")
    s = sub(s, "One tap. Then it opens like an app, even with no internet.",
            "One tap. Then open the guide from its new icon while you have signal and wait for <b>" + OK + "</b>.", n + " android lede")

    # 2. status pill and saved date
    s = sub(s, "st.textContent='Saved for offline use';", "st.textContent='Ready offline \\u2713';", n + " status")
    s, k = re.subn(r'(<span class="by">by PackSmart[^<]*</span>)</div>', r'\1<span class="by sv" id="savedOn" hidden></span></div>', s)
    if k != 1: sys.exit(f"{n}: byline not found ({k})")
    s = sub(s, PAINT, PAINT + SAVED_JS, n + " paint anchor")

    # 3. emergency block labels
    s = sub(s, '<p class="sec-h">Emergency (free, 24 hours)</p>', '<p class="sec-h">Emergency, anywhere in Japan (free, 24 hours)</p>', n + " emergency")
    s, k = re.subn(r'<p class="sec-h">(At [^<]+ only|At the stations?)</p>', r'<p class="sec-h">\1 (not for emergencies)</p>', s)
    if k != 1: sys.exit(f"{n}: info label not found ({k})")

    # 7. attribution codes
    s = sub(s, ".replace(/[^a-z0-9_-]/gi,'').slice(0,20)", ".replace(/[^a-z0-9_-]/gi,'').toLowerCase().slice(0,40)", n + " src")

    # 6. Narita health-form wording
    if key == "narita":
        s = sub(s, '"Hand in the plane\'s health form. Feeling unwell? Tell an officer."',
                '"Hand in the health form if your flight gave you one. Feeling unwell? Tell an officer."', n + " health form")

    # 4 + 5. connecting passengers and other-airport links (Narita and Haneda)
    css = CSS
    if key in CONN:
        fn, name = CONN[key]
        find_btn = ('<button type="button" class="conn slim" id="connBtn"><span class="ic" aria-hidden="true">&#128257;</span>'
                    '<span class="tx"><b>I&rsquo;m connecting to another flight</b></span><span class="go" aria-hidden="true">&rsaquo;</span></button>\n')
        arr_btn = ('<button type="button" class="conn" id="connBtn2"><span class="ic" aria-hidden="true">&#128257;</span>'
                   '<span class="tx"><b>I&rsquo;m connecting</b><small>Changing planes at ' + name + '? Tap here</small></span><span class="go" aria-hidden="true">&rsaquo;</span></button>\n')
        s = sub(s, '<div class="seg" id="seg"></div>\n', '<div class="seg" id="seg"></div>\n' + find_btn, n + " find button")
        s = sub(s, '<p class="lead2">Landed? Tap a step to tick it off.</p>\n', arr_btn + '<p class="lead2">Landed? Tap a step to tick it off.</p>\n', n + " arrive button")
        js = ("  /* I'm connecting: official connection guidance (w56) */\n"
              "  var CONN_HTML=" + json.dumps(fn(), ensure_ascii=True) + ";\n"
              "  (function(){\n"
              "    function openConn(from,btn){ try{ pgTrack('pg_connect',{from:from}); }catch(e){} openInfo('\\uD83D\\uDD01','Changing planes',CONN_HTML,btn); }\n"
              "    var b1=$('connBtn'), b2=$('connBtn2');\n"
              "    if(b1) b1.addEventListener('click',function(){ openConn('find',b1); });\n"
              "    if(b2) b2.addEventListener('click',function(){ openConn('arrive',b2); });\n"
              "  })();\n")
        s = sub(s, TICK, js + TICK, n + " tick anchor")
        links = " &middot; ".join(
            f'<a href="/{o}-pocket?src=pk_{key}" data-xg="{o}" data-via="arrive">{label}</a>' for o, label in OTHER[key])
        line = f'<p class="small xg2">Flying out of another airport later? {links}</p>\n'
        i = s.index('id="nextCard"'); eol = s.index("\n", i)
        if s.count('id="nextCard"') != 1: sys.exit(f"{n}: nextCard not unique")
        s = s[:eol + 1] + line + s[eol + 1:]
    s = sub(s, "</style>", css + "</style>", n + " style end")
    p.write_text(s, encoding="utf-8")
    print(f"  applied  {n}")


def fix_article(path):
    s = path.read_text(encoding="utf-8")
    if "Ready offline" in s:
        print(f"  already  {path.name}"); return
    s, k = re.subn(r"Open the ([A-Za-z -]+?) Pocket Guide once while you have signal, then add it to your home screen\. ",
                   r"Add the \1 Pocket Guide to your home screen first. Then open it from the icon while you have signal and wait for &ldquo;" + OK + "&rdquo;. ", s)
    if k != 1: sys.exit(f"{path.name}: pocket sentence not found ({k})")
    path.write_text(s, encoding="utf-8")
    print(f"  applied  {path.name}")


for key in PAGES:
    fix_pocket(key)
for art in ["narita-airport-guide", "haneda-airport-guide", "kansai-airport-guide", "tokyo-station-guide", "kyoto-station-guide", "osaka-station-guide", "shinjuku-station-guide", "ueno-station-guide"]:
    fix_article(PUB / "blog" / f"{art}.html")
