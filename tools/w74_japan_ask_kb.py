#!/usr/bin/env python3
"""
w74: the knowledge for "Ask about Japan" (/api/ask), built from the official-source research notes (24 Nov 2026).

The assistant may answer only from official sources: JR companies, airports, station and bus operators, JNTO and
city or government tourism pages (owner's rule, 24 Nov 2026). Those facts already sit in docs/research/*.md, each
with its source link and checked date. This script cuts the notes into short pieces for the assistant to search:

  * splits each file at its headings, then long sections into pieces of about 1,800 characters;
  * leaves out working sections that are not facts (photos, gaps, blocked hosts, owner notes) and local file names;
  * keeps the URLs found in each piece, so answers can cite the official page;
  * writes api/_japan_kb.js (the leading underscore keeps it from becoming an API route).

Add new official material as docs/research/<topic>-sources.md (facts with quotes, links and checked dates), then run:
    python3 tools/w74_japan_ask_kb.py
Idempotent: the output depends only on the notes. Aborts if fewer than 40 pieces come out.
"""
import glob, json, os, re, sys

ROOT = os.getcwd()
NOTES = sorted(glob.glob(os.path.join(ROOT, "docs", "research", "*-sources.md")))
OUT = os.path.join(ROOT, "api", "_japan_kb.js")
SKIP_HEAD = re.compile(r"photo|gap|blocked|pakutaso|how the timetable facts were read", re.I)
SKIP_LINE = re.compile(r"\bowner\b|TODO|PAKUTASO|sips|sandbox|proxy|curl|Playwright", re.I)
LOCAL_FILE = re.compile(r"\s*\[[^\]\n]*\.(?:html|pdf|json|png|jpe?g|webp)[^\]\n]*\]")
URL = re.compile(r"https?://[^\s)\]>\"'`,]+")
MAX = 900


def clean(text):
    lines = [l for l in text.splitlines() if not SKIP_LINE.search(l)]
    t = LOCAL_FILE.sub("", "\n".join(lines))
    return re.sub(r"\n{3,}", "\n\n", t).strip()


def pieces(path):
    label = os.path.basename(path).replace("-sources.md", "").replace("-", " ")
    text = open(path, encoding="utf-8").read()
    out, heads = [], []
    for block in re.split(r"(?m)^(?=#{1,4} )", text):
        m = re.match(r"(#{1,4}) (.*)", block)
        if m:
            lvl = len(m.group(1))
            heads = heads[:lvl - 1] + [m.group(2).strip()]
            body = block[m.end():]
        else:
            body = block
        if any(SKIP_HEAD.search(h) for h in heads):
            continue
        body = clean(body)
        if len(body) < 60:
            continue
        title = " > ".join([label] + heads)
        parts, cur = [], ""
        for para in re.split(r"\n(?=- |\n)", body):
            if cur and len(cur) + len(para) > MAX:
                parts.append(cur)
                cur = ""
            cur = (cur + "\n" + para).strip()
        if cur:
            parts.append(cur)
        for p in parts:
            urls = list(dict.fromkeys(u.rstrip(".;") for u in URL.findall(p)))
            out.append({"t": title, "x": p, "u": urls[:6]})
    return out


kb = []
for f in NOTES:
    kb += pieces(f)
if len(kb) < 40:
    sys.exit("w74 aborted: only %d pieces" % len(kb))
js = ("// Generated by tools/w74_japan_ask_kb.py from docs/research/*-sources.md. Do not edit by hand.\n"
      "export default " + json.dumps(kb, ensure_ascii=False, indent=0) + ";\n")
old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
if js != old:
    open(OUT, "w", encoding="utf-8").write(js)
print("w74 done. %d pieces from %d note files, %d KB%s." % (len(kb), len(NOTES), len(js) // 1024, "" if js != old else " (unchanged)"))
