#!/usr/bin/env python3
"""
w63: partner-link compliance on the articles (23 Nov 2026).

1. Every partner link must carry rel="nofollow noopener sponsored" (CLAUDE.md "Affiliate rules").
   An audit found 38 partner links on 16 pages with rel="noopener" or no rel at all, mostly
   hand-added in-text links. This adds the missing values, keeping any others.
2. Body copy carries no partner names and makes no promises of our own. The Portugal guide's
   transfer line ("Pre-book a Welcome Pickups airport transfer — no surge pricing, English-speaking
   drivers, fixed rates.") is reworded and labelled "(partner link)".

Run from the repo root:  python3 tools/w63_partner_link_labels.py
Idempotent: links that already have sponsored are left alone; the reworded line is matched exactly.
Japan pages and Pocket Guides are generated by other scripts and are not touched here.
"""
import glob, os, re, sys

ROOT = os.getcwd()
PUB = os.path.join(ROOT, "public")
AFF = re.compile(r"tpx\.li|tpo\.lu|tp\.media|travelpayouts|safetywing\.com|getyourguide\.com|klook\.com|welcomepickups|"
                 r"discovercars|airalo|yesim|tiqets|radicalstorage|p\.sakuramobile|japan-bullettrain|trip\.com/t/|12go")
SKIP_PAGES = ("japan-", "narita-", "haneda-", "kansai-", "tokyo-", "kyoto-", "osaka-", "shinjuku-", "ueno-", "new-chitose-", "sapporo-")

OLD_PT = ('🚕 <a href="https://tpx.li/qYFLwgZ8" target="_blank" rel="noopener" style="color:#00C9A7;text-decoration:underline;font-weight:600;">'
          'Pre-book a Welcome Pickups airport transfer</a> — no surge pricing, English-speaking drivers, fixed rates.')
NEW_PT = ('🚕 <a href="https://tpx.li/qYFLwgZ8" target="_blank" rel="nofollow noopener sponsored" style="color:#00C9A7;text-decoration:underline;font-weight:600;">'
          'Pre-book an airport transfer</a> (partner link): a driver meets you at arrivals, and the price is set when you book.')


def fix_rel(tag):
    m = re.search(r'\srel="([^"]*)"', tag)
    if m:
        vals = m.group(1).split()
        for v in ("nofollow", "noopener", "sponsored"):
            if v not in vals:
                vals.append(v)
        return tag[:m.start()] + ' rel="%s"' % " ".join(vals) + tag[m.end():]
    return tag[:-1].rstrip() + ' rel="nofollow noopener sponsored">'


changed, n_links = [], 0
files = sorted(glob.glob(os.path.join(PUB, "blog", "*.html"))) + sorted(glob.glob(os.path.join(PUB, "*.html")))
for path in files:
    base = os.path.basename(path)
    if base.startswith(SKIP_PAGES) or base.endswith("-pocket.html"):
        continue
    s = open(path, encoding="utf-8").read()
    orig = s
    if OLD_PT in s:
        s = s.replace(OLD_PT, NEW_PT)

    def rep(m):
        global n_links
        tag, href = m.group(0), m.group(1)
        if href.startswith("#") or not AFF.search(href) or "widget." in href or "tpwdg" in href:
            return tag
        rel = re.search(r'\srel="([^"]*)"', tag)
        if rel and "sponsored" in rel.group(1).split():
            return tag
        n_links += 1
        return fix_rel(tag)

    s = re.sub(r'<a\b[^>]*\bhref="([^"]+)"[^>]*>', rep, s)
    if s != orig:
        open(path, "w", encoding="utf-8").write(s)
        changed.append(base)
print("w63 done. %d link(s) labelled sponsored on %d page(s)%s" % (
    n_links, len(changed), "".join("\n  - " + c for c in changed)))
