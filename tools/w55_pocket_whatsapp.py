#!/usr/bin/env python3
"""w55: a WhatsApp share button, always visible at the bottom right of every Pocket Guide.

Post-processor. Run LAST, after the pocket-guide chain (w44 to w49), because the pocket pages are
regenerated by w25 / w31 / w35 / w36 / w39 / w42. Idempotent (marker: id="waShare").

A green pill (icon + 'Share this') floats just above the bottom tab bar on the right (the usual place for a chat/share
button). Below the scrim (z 5 < 7) so an open sheet dims it. On wide screens it stays next to the 560px column.
Extra padding at the end of each panel so the button never hides the last lines.

The link is a plain wa.me link with a ready message and the guide address tagged ?src=wa, so opens from a
shared message show up in the existing pg_open event (PG Source = wa). A tap is counted as pg_share with
via=whatsapp (counts the tap, not completion).
"""
import pathlib, re, sys
from urllib.parse import quote

PUB = pathlib.Path(__file__).resolve().parent.parent / "public"
PAGES = ["narita", "haneda", "kix", "kyoto", "osaka", "tokyo", "shinjuku", "ueno", "new-chitose", "sapporo"]

ICON = ('<svg viewBox="0 0 24 24" width="28" height="28" aria-hidden="true" focusable="false">'
        '<path d="M12 2.6a9.4 9.4 0 0 0-8 14.3L2.8 21.4l4.6-1.2A9.4 9.4 0 1 0 12 2.6z" fill="none" stroke="#fff" stroke-width="1.7" stroke-linejoin="round"/>'
        '<path transform="translate(6.3 6.1) scale(.5)" fill="#fff" d="M22 16.92v3a2 2 0 0 1-2.18 2 19.79 19.79 0 0 1-8.63-3.07 19.5 19.5 0 0 1-6-6 '
        '19.79 19.79 0 0 1-3.07-8.67A2 2 0 0 1 4.11 2h3a2 2 0 0 1 2 1.72 12.84 12.84 0 0 0 .7 2.81 2 2 0 0 1-.45 2.11L8.09 9.91a16 16 0 0 0 6 6l1.27-1.27'
        'a2 2 0 0 1 2.11-.45 12.84 12.84 0 0 0 2.81.7A2 2 0 0 1 22 16.92z"/></svg>')

CSS = ('.wa{position:fixed;z-index:5;right:max(14px,calc((100vw - 560px)/2 + 14px));bottom:calc(var(--tabh) + 14px);'
       'height:50px;padding:0 20px 0 12px;border-radius:25px;background:#128C7E;color:#fff;display:flex;align-items:center;gap:8px;'
       'font:800 1.05rem/1 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;text-decoration:none;white-space:nowrap;'
       'box-shadow:0 3px 12px rgba(0,0,0,.35);-webkit-tap-highlight-color:transparent}'
       '.wa:active{transform:scale(.94)}.wa:focus-visible{outline:3px solid #0f0f23;outline-offset:2px}'
       '.panels{padding-bottom:84px}'
       '@media print{.wa{display:none}}\n')

JS_OLD = "    if(/^mailto:/i.test(h)) return;\n"
JS_NEW = ("    if(/^mailto:/i.test(h)) return;\n"
          "    if(a.id==='waShare'){ pgTrack('pg_share',{via:'whatsapp'}); return; }\n")

for key in PAGES:
    p = PUB / f"{key}-pocket.html"
    s = p.read_text(encoding="utf-8")
    if 'id="waShare"' in s and '<span>Share this</span>' not in s:
        sys.exit(f"older WhatsApp button in {p.name}: regenerate the page first")
    if 'id="waShare"' in s:
        print(f"  already  {p.name}"); continue
    if 'class="wa"' in s: sys.exit(f"old header icon found in {p.name}: regenerate the page first")
    m = re.search(r"<header class=\"top\">\n<div><strong>([^<]*Pocket Guide)</strong>", s)
    if not m: sys.exit(f"no header in {p.name}")
    title = m.group(1)
    url = f"https://www.packsmartapp.com/{key}-pocket?src=wa"
    text = f"{title}: free, and it works with no internet once you open it. {url}"
    link = (f'<a class="wa" id="waShare" href="https://wa.me/?text={quote(text, safe="")}" target="_blank" rel="noopener" '
            f'aria-label="Share this guide on WhatsApp">{ICON}<span>Share this</span></a>\n')
    nav = '<nav class="tabs"'
    if s.count(nav) != 1: sys.exit(f"tabs nav not unique in {p.name}")
    s = s.replace(nav, link + nav)
    if s.count("</style>") != 1: sys.exit(f"style end not unique in {p.name}")
    s = s.replace("</style>", CSS + "</style>")
    if s.count(JS_OLD) != 1: sys.exit(f"js anchor not unique in {p.name}")
    s = s.replace(JS_OLD, JS_NEW)
    p.write_text(s, encoding="utf-8")
    print(f"  applied  {p.name}  ({title})")
