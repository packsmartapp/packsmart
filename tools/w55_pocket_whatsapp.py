#!/usr/bin/env python3
"""w55: a small WhatsApp share icon, always visible in the header of every Pocket Guide.

Post-processor. Run LAST, after the pocket-guide chain (w44 to w49), because the pocket pages are
regenerated by w25 / w31 / w35 / w36 / w39 / w42. Idempotent (marker: id="waShare").

The link is a plain wa.me link with a ready message and the guide address tagged ?src=wa, so opens from a
shared message show up in the existing pg_open event (PG Source = wa). A tap on the icon is counted as
pg_share with via=whatsapp (counts the tap, not completion).
"""
import pathlib, re, sys
from urllib.parse import quote

PUB = pathlib.Path(__file__).resolve().parent.parent / "public"
PAGES = ["narita", "haneda", "kix", "kyoto", "osaka", "tokyo"]

ICON = ('<svg viewBox="0 0 24 24" width="22" height="22" aria-hidden="true" focusable="false">'
        '<path d="M12 2.6a9.4 9.4 0 0 0-8 14.3L2.8 21.4l4.6-1.2A9.4 9.4 0 1 0 12 2.6z" fill="none" stroke="#fff" stroke-width="1.7" stroke-linejoin="round"/>'
        '<path transform="translate(6.3 6.1) scale(.5)" fill="#fff" d="M22 16.92v3a2 2 0 0 1-2.18 2 19.79 19.79 0 0 1-8.63-3.07 19.5 19.5 0 0 1-6-6 '
        '19.79 19.79 0 0 1-3.07-8.67A2 2 0 0 1 4.11 2h3a2 2 0 0 1 2 1.72 12.84 12.84 0 0 0 .7 2.81 2 2 0 0 1-.45 2.11L8.09 9.91a16 16 0 0 0 6 6l1.27-1.27'
        'a2 2 0 0 1 2.11-.45 12.84 12.84 0 0 0 2.81.7A2 2 0 0 1 22 16.92z"/></svg>')

CSS_BASE = (".status{margin-left:auto}"
            ".wa{flex:none;display:inline-flex;align-items:center;justify-content:center;width:40px;height:40px;border-radius:50%;background:#25D366;"
            "box-shadow:0 1px 6px rgba(0,0,0,.3);-webkit-tap-highlight-color:transparent}"
            ".wa:active{transform:scale(.94)}.wa:focus-visible{outline:3px solid #fff;outline-offset:2px}")
# phones: keep the header on two lines (it was 68px tall before the icon; 64px now at 360px and wider)
CSS_COMPACT = ("@media(max-width:420px){.top{gap:8px}.top strong{font-size:1.02rem}.top .by{font-size:.72rem}"
               ".status{font-size:.72rem;padding:4px 8px}.wa{width:34px;height:34px}.wa svg{width:20px;height:20px}}.wa{position:relative}.wa::after{content:"";position:absolute;inset:-5px}")
CSS = CSS_BASE + CSS_COMPACT + "\n"

JS_OLD = "    if(/^mailto:/i.test(h)) return;\n"
JS_NEW = ("    if(/^mailto:/i.test(h)) return;\n"
          "    if(a.id==='waShare'){ pgTrack('pg_share',{via:'whatsapp'}); return; }\n")

for key in PAGES:
    p = PUB / f"{key}-pocket.html"
    s = p.read_text(encoding="utf-8")
    if 'id="waShare"' in s:
        if CSS_COMPACT in s:
            print(f"  already  {p.name}"); continue
        if CSS_BASE not in s: sys.exit(f"base css missing in {p.name}")
        p.write_text(s.replace(CSS_BASE, CSS_BASE + CSS_COMPACT), encoding="utf-8")
        print(f"  upgraded {p.name} (compact header)"); continue
    m = re.search(r"<header class=\"top\">\n<div><strong>([^<]*Pocket Guide)</strong>", s)
    if not m: sys.exit(f"no header in {p.name}")
    title = m.group(1)
    url = f"https://www.packsmartapp.com/{key}-pocket?src=wa"
    text = f"{title}: free, and it works with no internet once you open it. {url}"
    link = (f'<a class="wa" id="waShare" href="https://wa.me/?text={quote(text, safe="")}" target="_blank" rel="noopener" '
            f'aria-label="Share this guide on WhatsApp">{ICON}</a>\n')
    status = '<div class="status" id="status" role="status">Checking...</div>\n'
    if s.count(status) != 1: sys.exit(f"status block not unique in {p.name}")
    s = s.replace(status, status + link)
    anchor = ".status.off{background:#FFB84D;color:#3a2400}\n"
    if s.count(anchor) != 1: sys.exit(f"css anchor not unique in {p.name}")
    s = s.replace(anchor, anchor + CSS)
    if s.count(JS_OLD) != 1: sys.exit(f"js anchor not unique in {p.name}")
    s = s.replace(JS_OLD, JS_NEW)
    p.write_text(s, encoding="utf-8")
    print(f"  applied  {p.name}  ({title})")
